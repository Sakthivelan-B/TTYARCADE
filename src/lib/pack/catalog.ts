export type PackMode = "solo" | "local" | "online";
export type PackGame = {
  id: string;
  name: string;
  category: PackCategory;
  desc: string;
  rules: string;
  min: number;
  max: number;
  modes: PackMode[];
  endless: true;
};
const solo: PackMode[] = ["solo", "local"],
  versus: PackMode[] = ["local", "online"];
function g(
  id: string,
  name: string,
  category: PackCategory,
  desc: string,
  rules: string,
  modes: PackMode[] = solo,
  min = 1,
  max = 6,
): PackGame {
  return { id, name, category, desc, rules, modes, min, max, endless: true };
}

import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PACK_GAMES} from '../src/lib/pack/catalog.ts';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3000';
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage();
const errors = []; page.on('pageerror', e => errors.push(page.url() + ': ' + e.message));
const games = fs.readdirSync('src/app/games').filter(g => g !== '[game]' && fs.existsSync(`src/app/games/${g}/page.tsx`));
games.push(...PACK_GAMES.map(g=>g.id));
const routes = ['/', '/account', '/admin', '/settings', '/login', '/leaderboard', '/games/crazy8/rules', ...games.map(g => '/games/' + g)];
for (const route of routes) {
  const r = await page.goto(base + route); assert.equal(r.status(), 200, route);
  await page.locator('main').waitFor();
  const theme = await page.evaluate(() => ({ bg: getComputedStyle(document.body).backgroundColor, fg: getComputedStyle(document.body).color, visual: document.querySelectorAll('canvas,img,svg,video').length }));
  assert.equal(theme.bg, 'rgb(0, 0, 0)', route); assert.equal(theme.fg, 'rgb(255, 255, 255)', route); assert.equal(theme.visual, 0, route);
  const links = await page.locator('a[href^="/"]').evaluateAll(es => es.map(e => e.getAttribute('href').split('?')[0]));
  for (const link of links) assert.ok(routes.includes(link), `unknown internal link ${link} from ${route}`);
}
await page.evaluate(() => localStorage.setItem('ttyarcade-theme', 'light'));
await page.goto(base + '/games/snake');
assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(0, 0, 0)');
await page.getByRole('button', { name: 'start', exact: true }).click();
await page.keyboard.press('ArrowUp'); await page.keyboard.press('a');
await page.waitForTimeout(200);
assert.ok((await page.locator('pre.screen').textContent()).includes('@'));
await page.goto(base + '/games/2048');
const start = page.getByRole('button', { name: /start|new game/i }).first();
if (await start.count()) await start.click();
for (const key of ['ArrowUp', 'a', 'ArrowDown', 'd']) await page.keyboard.press(key);
await page.goto(base + '/games/pong'); await page.getByRole('button', { name: 'start', exact: true }).click();
await page.keyboard.press('w'); await page.waitForTimeout(100);
await page.goto(base + '/games/sequence'); await page.getByRole('button', { name: 'start', exact: true }).click();
await page.goto(base + '/'); await page.waitForTimeout(1000);
// A human cannot steal the CPU turn; online CPU uses the actual turn guard.
await page.goto(base + '/games/tictactoe');
await page.getByRole('button', { name: 'vs cpu (easy)', exact: true }).click();
await page.locator('button.cell').nth(0).click();
assert.equal(await page.locator('button.cell').nth(1).isDisabled(), true);
await page.waitForTimeout(650);
assert.equal(await page.locator('button.cell').filter({ hasText: /^O$/ }).count(), 1);
const created = await (await page.request.post(base + '/api/rooms', { data: { game: 'tictactoe', name: 'browserhost' } })).json();
await page.request.post(base + '/api/rooms/' + created.room.code, { data: { action: 'bots', token: created.me.token, count: 1 } });
await page.evaluate(({code,token}) => localStorage.setItem('ttyarcade-room:' + code, token), { code: created.room.code, token: created.me.token });
await page.goto(base + '/games/tictactoe?room=' + created.room.code);
await page.getByRole('button', { name: 'start game', exact: true }).click();
await page.locator('button.cell').nth(0).click();
await page.locator('button.cell').filter({ hasText: /^O$/ }).waitFor({ timeout: 12000 });
assert.deepEqual(errors, []);
await browser.close();
console.log(`PASS: ${routes.length} routes, internal links, strict terminal colors, text-only DOM, saved-light override, game input, local/online CPU and navigation smoke tests; no browser page errors.`);
